def get_k8s_nodes():
    try:
        if not os.path.exists(KUBECONFIG_FILE):
            return {"success": False, "error": "kubeconfig not found", "nodes": []}

        result = subprocess.run(
            ["kubectl", "--kubeconfig", KUBECONFIG_FILE, "get", "nodes", "-o", "yaml"],
            capture_output=True, text=True, timeout=30
        )

        if result.returncode == 0:
            data = yaml.safe_load(result.stdout)
            items = data.get("items", [])
            nodes = []

            for item in items:
                status = item.get("status", {})
                conditions = status.get("conditions", [])
                ready = next((c for c in conditions if c.get("type") == "Ready"), {})
                roles = []
                labels = item.get("metadata", {}).get("labels", {})

                if labels.get("node-role.kubernetes.io/master") == "true":
                    roles.append("master")
                if labels.get("node-role.kubernetes.io/control-plane") == "true":
                    roles.append("control-plane")
                if labels.get("node-role.kubernetes.io/worker") == "true":
                    roles.append("worker")

                # Calculate uptime from node creation timestamp
                creation_ts = item.get("metadata", {}).get("creationTimestamp", None)
                uptime = "-"
                if creation_ts:
                    try:
                        ts = datetime.fromisoformat(creation_ts.replace("Z", "+00:00"))
                        now = datetime.now(timezone.utc)
                        delta = now - ts
                        days = delta.days
                        hours, remainder = divmod(delta.seconds, 3600)
                        minutes = remainder // 60
                        if days > 0:
                            uptime = f"{days}d {hours}h"
                        elif hours > 0:
                            uptime = f"{hours}h {minutes}m"
                        else:
                            uptime = f"{minutes}m"
                    except:
                        pass

                nodes.append({
                    "name": item.get("metadata", {}).get("name"),
                    "roles": roles,
                    "status": ready.get("status", "Unknown"),
                    "version": status.get("nodeInfo", {}).get("kubeletVersion", "-"),
                    "age": item.get("metadata", {}).get("creationTimestamp", "-"),
                    "cpu": status.get("allocatable", {}).get("cpu", "-"),
                    "memory": status.get("allocatable", {}).get("memory", "-"),
                    "uptime": uptime
                })
            return {"success": True, "nodes": nodes}
        return {"success": False, "error": result.stderr, "nodes": []}
    except Exception as e:
        return {"success": False, "error": str(e), "nodes": []}

def get_worker_names_to_remove(old_count, new_count):
    if old_count <= new_count:
        return []
    workers = []
    for i in range(new_count + 1, old_count + 1):
        workers.append(f"rke2-worker-{i:02d}")
    return workers

def get_all_worker_nodes():
    if not os.path.exists(KUBECONFIG_FILE):
        return []
    try:
        result = subprocess.run(
            ["kubectl", "--kubeconfig", KUBECONFIG_FILE, "get", "nodes", "-o", "jsonpath={.items[*].metadata.name}"],
            capture_output=True, text=True, timeout=30
        )
        if result.returncode == 0:
            all_nodes = result.stdout.strip().split()
            return [n for n in all_nodes if n.startswith("rke2-worker-")]
    except Exception:
        pass
    return []

def k8s_scale_down_workers(worker_names):
    if not os.path.exists(KUBECONFIG_FILE):
        return {"success": False, "error": "kubeconfig not found", "results": []}

    results = []
    for worker_name in worker_names:
        action_result = {"worker": worker_name, "steps": []}

        for action, cmd in [
            ("cordon", ["kubectl", "--kubeconfig", KUBECONFIG_FILE, "cordon", worker_name]),
            ("drain", ["kubectl", "--kubeconfig", KUBECONFIG_FILE, "drain", worker_name, "--ignore-daemonsets", "--delete-emptydir-data", "--force", "--grace-period=30", "--timeout=120s"]),
            ("delete_node", ["kubectl", "--kubeconfig", KUBECONFIG_FILE, "delete", "node", worker_name, "--grace-period=0", "--force"])
        ]:
            try:
                result = subprocess.run(cmd, capture_output=True, text=True, timeout=180)
                action_result["steps"].append({"action": action, "success": result.returncode == 0, "output": result.stdout + result.stderr})
            except Exception as e:
                action_result["steps"].append({"action": action, "success": False, "output": str(e)})

        results.append(action_result)

    all_success = all(all(step["success"] for step in r["steps"]) for r in results)
    return {"success": all_success, "results": results}

