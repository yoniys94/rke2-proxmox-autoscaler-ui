@app.route("/api/proxmox/resources", methods=["GET", "POST"])
def proxmox_resources():
    """Get available nodes and templates from Proxmox"""
    env = load_env()

    # Support POST with inline credentials (for setup wizard)
    if request.method == "POST":
        data = request.get_json() or {}
        endpoint = data.get("proxmox_endpoint", "")
        username = data.get("proxmox_username", "")
        password = data.get("proxmox_password", "")
    else:
        endpoint = env.get("PROXMOX_ENDPOINT", "")
        username = env.get("PROXMOX_USERNAME", "")
        password = env.get("PROXMOX_PASSWORD", "")

    if not all([endpoint, username, password]):
        return jsonify({"error": "Proxmox not configured"}), 400

    try:
        from proxmoxer import ProxmoxAPI
        import urllib3
        urllib3.disable_warnings()

        # Extract host and port from endpoint
        host = endpoint.replace("https://", "").split(":")[0]
        port = int(endpoint.split(":")[-1].replace("/api2/json", "").strip())

        proxmox = ProxmoxAPI(host, port=port, user=username, password=password, verify_ssl=False)

        # Get nodes
        all_nodes = []
        try:
            for node in proxmox.nodes.get():
                all_nodes.append({
                    "node": node.get("node"),
                    "status": node.get("status", "unknown")
                })
        except Exception as e:
            return jsonify({"error": f"Failed to get nodes: {str(e)}"}), 500

        # Get templates from each node
        templates = {}
        for node_info in all_nodes:
            node_name = node_info["node"]
            try:
                qemu = proxmox.nodes(node_name).qemu.get()
                node_templates = []
                for v in qemu:
                    if v.get("template") == 1:
                        node_templates.append({
                            "vmid": v.get("vmid"),
                            "name": v.get("name")
                        })
                if node_templates:
                    templates[node_name] = node_templates
            except:
                pass

        return jsonify({
            "success": True,
            "nodes": all_nodes,
            "templates": templates
        })

    except Exception as e:
        return jsonify({"error": str(e)}), 500

@app.route("/api/config", methods=["POST"])
def save_config():
    data = request.get_json()
    required = ["proxmox_endpoint", "proxmox_username", "proxmox_password", "kubeconfig_content", "vm_password"]
    for field in required:
        if not data.get(field):
            return jsonify({"error": f"{field} is required"}), 400

    # Write kubeconfig to file
    with open(KUBECONFIG_FILE, "w") as f:
        f.write(data["kubeconfig_content"])

    # Generate a simple token if not exists
    import secrets
    import json
    token = secrets.token_hex(32)

    # Handle template_per_node
    template_per_node = data.get("template_per_node", {})
    if isinstance(template_per_node, dict):
        template_per_node_str = json.dumps(template_per_node)
    else:
        template_per_node_str = str(template_per_node)

    # Save env
    env_data = {
        "PROXMOX_ENDPOINT": data["proxmox_endpoint"],
        "PROXMOX_USERNAME": data["proxmox_username"],
        "PROXMOX_PASSWORD": data["proxmox_password"],
        "VM_PASSWORD": data["vm_password"],
        "KUBECONFIG_PATH": KUBECONFIG_FILE,
        "DASHBOARD_TOKEN": token,
        "DASHBOARD_PASSWORD": data.get("dashboard_password", secrets.token_hex(8)),
        "TEMPLATE_PER_NODE": template_per_node_str
    }
    save_env(env_data)

    return jsonify({"success": True, "message": "Configuration saved", "token": token})

