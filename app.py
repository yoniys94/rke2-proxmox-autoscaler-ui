@app.route("/api/scale-down", methods=["POST"])
@require_auth
def scale_down():
    """Handle scale down - cordon & drain, but DON'T delete K8s node yet"""
    data = request.get_json()
    new_worker_count = data.get("worker_count")

    if new_worker_count is None:
        return jsonify({"error": "worker_count required"}), 400

    current_count = get_current_worker_count()

    if new_worker_count >= current_count:
        set_var_in_tfvars("worker_count", new_worker_count)
        tf_result = run_terraform("apply")
        return jsonify({"action": "scale_up_or_same", "worker_count": new_worker_count, "terraform": tf_result})

    workers_to_remove = get_worker_names_to_remove(current_count, new_worker_count)

    if new_worker_count == 0:
        workers_to_remove = get_all_worker_nodes()

    # Update terraform.tfvars first
    set_var_in_tfvars("worker_count", new_worker_count)

    # Only cordon & drain - DON'T delete K8s node yet
    k8s_result = k8s_cordon_drain_workers(workers_to_remove)

    # Run terraform apply (this will delete the VMs)
    tf_result = run_terraform("apply")

    return jsonify({
        "action": "scale_down",
        "worker_count": new_worker_count,
        "workers_removed": workers_to_remove,
        "k8s_drain": k8s_result,
        "terraform": tf_result,
        "note": "K8s nodes still exist. Use 'Delete Node' button to remove them."
    })


def k8s_cordon_drain_workers(worker_names):
    """Cordon and drain K8s nodes (without deleting)"""
    if not os.path.exists(KUBECONFIG_FILE):
        return {"success": False, "error": "kubeconfig not found", "results": []}

    results = []
    for worker_name in worker_names:
        action_result = {"worker": worker_name, "steps": []}

        # Step 1: Cordon
        try:
            result = subprocess.run(
                ["kubectl", "--kubeconfig", KUBECONFIG_FILE, "cordon", worker_name],
                capture_output=True, text=True, timeout=30
            )
            action_result["steps"].append({
                "action": "cordon",
                "success": result.returncode == 0,
                "output": result.stdout + result.stderr
            })
        except Exception as e:
            action_result["steps"].append({"action": "cordon", "success": False, "output": str(e)})

        # Step 2: Drain
        try:
            result = subprocess.run(
                ["kubectl", "--kubeconfig", KUBECONFIG_FILE, "drain", worker_name,
                 "--ignore-daemonsets", "--delete-emptydir-data", "--force",
                 "--grace-period=30", "--timeout=120s"],
                capture_output=True, text=True, timeout=180
            )
            action_result["steps"].append({
                "action": "drain",
                "success": result.returncode == 0,
                "output": result.stdout + result.stderr
            })
        except Exception as e:
            action_result["steps"].append({"action": "drain", "success": False, "output": str(e)})

        results.append(action_result)

    all_success = all(all(step["success"] for step in r["steps"]) for r in results)
    return {"success": all_success, "results": results}

