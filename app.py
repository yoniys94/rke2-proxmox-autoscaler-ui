def run_terraform(action="plan"):
    try:
        os.chdir(TERRAFORM_DIR)
        env = load_env()

        # Set Terraform environment variables from .env
        tf_env = os.environ.copy()
        if env.get("PROXMOX_ENDPOINT"):
            tf_env["TF_VAR_proxmox_endpoint"] = env["PROXMOX_ENDPOINT"]
        if env.get("PROXMOX_USERNAME"):
            tf_env["TF_VAR_proxmox_username"] = env["PROXMOX_USERNAME"]
        if env.get("PROXMOX_PASSWORD"):
            tf_env["TF_VAR_proxmox_password"] = env["PROXMOX_PASSWORD"]
        if env.get("VM_PASSWORD"):
            tf_env["TF_VAR_vm_password"] = env["VM_PASSWORD"]

        # Auto init if needed (idempotent, safe for existing state)
        init_result = subprocess.run(
            ["terraform", "init", "-no-color"],
            capture_output=True, text=True, timeout=120, env=tf_env
        )
        if init_result.returncode != 0:
            return {"success": False, "output": "Init failed: " + init_result.stdout + init_result.stderr}

        if action == "plan":
            result = subprocess.run(["terraform", "plan", "-no-color"], capture_output=True, text=True, timeout=60, env=tf_env)
        else:
            result = subprocess.run(["terraform", "apply", "-auto-approve", "-no-color"], capture_output=True, text=True, timeout=300, env=tf_env)
        return {"success": result.returncode == 0, "output": result.stdout + result.stderr}
    except subprocess.TimeoutExpired:
        return {"success": False, "output": "Timeout: Terraform took too long"}
    except Exception as e:
        return {"success": False, "output": str(e)}

def get_terraform_status():
    try:
        result = subprocess.run(["terraform", "show", "-json"], capture_output=True, text=True, cwd=TERRAFORM_DIR, timeout=30)
        if result.returncode == 0:
            import json
            data = json.loads(result.stdout)
            resources = data.get("values", {}).get("root_module", {}).get("resources", [])
            workers = [r for r in resources if r.get("type") == "proxmox_virtual_environment_vm"]
            return {"success": True, "workers": len(workers), "resources": workers}
        return {"success": False, "workers": 0, "resources": []}
    except Exception:
        return {"success": False, "workers": 0, "resources": []}

